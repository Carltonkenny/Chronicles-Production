class TestFFmpegAssembler:
    def test_assembler_creates_minimal_mp4(self):
        from post.assembler import FFmpegAssembler
        import tempfile

        assembler = FFmpegAssembler(output_dir=Path(tempfile.mkdtemp()))
        result = assembler.assemble(
            story_hash="test_assembler",
            assembly_timeline=None,
            clip_data=None,
        )
        # FFmpeg may not be available on all systems
        if result:
            assert result.exists()
            assert result.suffix == ".mp4"
            result.unlink()

    def test_assembler_output_dir_created(self):
        from post.assembler import FFmpegAssembler
        import tempfile

        d = Path(tempfile.mkdtemp())
        assembler = FFmpegAssembler(output_dir=d / "films")
        assert assembler.output_dir.exists()

    def test_assembler_handles_empty_clips(self):
        from post.assembler import FFmpegAssembler
        import tempfile

        d = Path(tempfile.mkdtemp())
        assembler = FFmpegAssembler(output_dir=d)
        result = assembler._create_minimal_mp4("test_empty", {"title_card": {"text": "Test"}})
        if result:
            assert result.exists()
            result.unlink()
