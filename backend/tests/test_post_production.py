class TestEditorAgent:
    def test_editor_agent_type(self):
        from agents.editor import EditorAgent
        agent = EditorAgent()
        assert agent.agent_type == "editor"

    @pytest.mark.asyncio
    async def test_editor_empty_scenes(self, monkeypatch):
        async def mock_llm(*args, **kwargs):
            return json.dumps({
                "title_card": {"text": "Test", "subtitle": "", "duration_s": 3.0},
                "scenes": [],
                "credits": {"text": "Test credits", "duration_s": 4.0},
                "total_duration_s": 7.0,
            })

        monkeypatch.setattr("agents.editor.call_llm", mock_llm)
        from agents.editor import EditorAgent
        from schemas import WorkOrder

        agent = EditorAgent()
        wo = WorkOrder(
            agent_type="editor",
            input_data={
                "title": "Test Film",
                "culture": "viking",
                "timeline": "high_medieval",
                "theme": "ambition",
                "scenes": [],
                "clip_data": [],
                "target_duration_s": 90,
            },
            story_hash="test",
            priority=1,
        )
        result = await agent.execute(wo)
        assert result.success is True
        timeline = result.output_data.get("assembly_timeline", {})
        assert "title_card" in timeline
        assert "credits" in timeline

